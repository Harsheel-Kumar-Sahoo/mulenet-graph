"""Dataset containers + CSV/JSON IO. ALL DATA IS SYNTHETIC."""
import csv, json
from collections import Counter
from dataclasses import dataclass, asdict
from pathlib import Path

TXN_FIELDS = ["txn_id", "ts", "src", "dst", "amount", "kind", "label", "group_id", "scenario"]
ACC_FIELDS = ["id", "type", "label", "ring_id", "hardneg_id", "hardneg_type"]
NOTE = "SYNTHETIC DATA ONLY. Generated by MuleNet-Graph. No real UPI/bank/customer data.\n"


@dataclass
class Txn:
    txn_id: int
    ts: float          # seconds since start of simulation
    src: str
    dst: str
    amount: float      # INR
    kind: str          # peer|merchant|bill|mule_<pattern>|camouflage|hn_<type>
    label: int = 0     # 1 = part of a mule-ring money flow
    group_id: str = "" # ring id / hard-negative id
    scenario: str = "normal"  # normal | ring | ring_camouflage | hardneg:<type>


@dataclass
class Dataset:
    txns: list
    accounts: dict        # id -> {type,label,ring_id?,hardneg_id?,hardneg_type?}
    rings: list           # ring metadata dicts (ground truth)
    hard_negatives: list  # hard-negative metadata dicts
    meta: dict

    def finalize(self):
        self.txns.sort(key=lambda t: (t.ts, t.src, t.dst))
        for i, t in enumerate(self.txns):
            t.txn_id = i
        return self

    def summary(self) -> dict:
        return {
            "n_txns": len(self.txns), "n_accounts": len(self.accounts),
            "n_mule_txns": sum(t.label for t in self.txns),
            "n_mule_accounts": sum(a["label"] for a in self.accounts.values()),
            "rings_by_pattern": dict(Counter(r["pattern"] for r in self.rings)),
            "hardneg_by_type": dict(Counter(h["type"] for h in self.hard_negatives)),
            "txns_by_scenario": dict(Counter(t.scenario.split(":")[0] for t in self.txns)),
        }

    def save(self, out_dir):
        out = Path(out_dir); out.mkdir(parents=True, exist_ok=True)
        with open(out / "txns.csv", "w", newline="") as f:
            w = csv.writer(f); w.writerow(TXN_FIELDS)
            for t in self.txns:
                w.writerow([t.txn_id, t.ts, t.src, t.dst, t.amount, t.kind, t.label, t.group_id, t.scenario])
        with open(out / "accounts.csv", "w", newline="") as f:
            w = csv.writer(f); w.writerow(ACC_FIELDS)
            for k, a in self.accounts.items():
                w.writerow([k, a["type"], a["label"], a.get("ring_id", ""), a.get("hardneg_id", ""), a.get("hardneg_type", "")])
        (out / "scenarios.json").write_text(json.dumps(
            {"meta": self.meta, "rings": self.rings, "hard_negatives": self.hard_negatives}, indent=1))
        (out / "README.txt").write_text(NOTE)

    @staticmethod
    def load(out_dir) -> "Dataset":
        out = Path(out_dir)
        with open(out / "txns.csv", newline="") as f:
            txns = [Txn(int(r["txn_id"]), float(r["ts"]), r["src"], r["dst"], float(r["amount"]),
                        r["kind"], int(r["label"]), r["group_id"], r["scenario"]) for r in csv.DictReader(f)]
        with open(out / "accounts.csv", newline="") as f:
            accounts = {r["id"]: {"type": r["type"], "label": int(r["label"]), "ring_id": r["ring_id"],
                                  "hardneg_id": r["hardneg_id"], "hardneg_type": r["hardneg_type"]}
                        for r in csv.DictReader(f)}
        sc = json.loads((out / "scenarios.json").read_text())
        return Dataset(txns, accounts, sc["rings"], sc["hard_negatives"], sc["meta"])
